/** Deterministic pseudo-random generator; called lazily (never at module scope). */
export function getAccidentRecords() {
  let s = 42;
  const rnd = () => (s = (s * 9301 + 49297) % 233280) / 233280;
  const sev = ["Fatal", "Grievous", "Minor", "Damage only"];
  const veh = [
    "Car / Two-wheeler",
    "Truck / Car",
    "Bus / Pedestrian",
    "Two-wheeler only",
    "Auto / Two-wheeler",
  ];
  const weather = ["Clear", "Clear", "Clear", "Rain", "Fog"];
  const tod = ["Morning", "Afternoon", "Evening", "Night"];
  const out = [];
  BLACKSPOTS.forEach((b) => {
    for (let i = 0; i < b.accidents; i++) {
      const year = 2020 + Math.floor(rnd() * 5);
      const m = 1 + Math.floor(rnd() * 12);
      const d = 1 + Math.floor(rnd() * 28);
      const t = tod[Math.floor(rnd() * 4)] ?? "Morning";
      const h = { Morning: 8, Afternoon: 14, Evening: 19, Night: 23 }[t] ?? 12;
      const sv = sev[Math.min(3, Math.floor(rnd() * 4))] ?? "Minor";
      out.push({
        id: `ACC-${10000 + out.length + 1}`,
        datetime: `${year}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}T${String(h).padStart(2, "0")}:${String(Math.floor(rnd() * 60)).padStart(2, "0")}`,
        area: b.area,
        location: b.name,
        lat: +(b.lat + (rnd() - 0.5) * 0.004).toFixed(5),
        lng: +(b.lng + (rnd() - 0.5) * 0.004).toFixed(5),
        injuries: sv === "Damage only" ? 0 : 1 + Math.floor(rnd() * 3),
        fatalities: sv === "Fatal" ? 1 : 0,
        severity: sv,
        vehicles: veh[Math.floor(rnd() * veh.length)] ?? "Car / Two-wheeler",
        weather: weather[Math.floor(rnd() * 5)] ?? "Clear",
        timeOfDay: t,
      });
    }
  });
  return out.sort((a, b) => b.datetime.localeCompare(a.datetime));
}
